"""PDF rendering with ReportLab in invariant mode, so the same invoice gives the same bytes.

Every value in `Invoice.fields` is printed exactly as it is serialised in the ground truth.
The "SYNTHETIC" watermark is drawn horizontally in its own band: a rotated watermark would
interleave its letters with the invoice text in pdfplumber's extraction.
"""

import io

from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import simpleSplit
from reportlab.pdfgen import canvas

from synth.master import COUNTRIES
from synth.model import Invoice, fmt_money, fmt_qty

WATERMARK = "SYNTHETIC"
DISCLAIMER = (
    "SYNTHETIC TEST DOCUMENT - fictional vendor and bank details generated by invoice-agent "
    "synth. Not a real invoice."
)
BUYER = (
    "Demo Buyer Synthetica B.V.",
    "Testlaan 1, 1000 AA Amsterdam, Netherlands",
    "VAT ID: NL990000001B01",
)

PAGE_W, PAGE_H = A4
LEFT = 50.0
RIGHT = PAGE_W - 50.0
FONT = "Helvetica"
BOLD = "Helvetica-Bold"
GRAY = (0.45, 0.45, 0.45)
LIGHT = (0.8, 0.8, 0.8)
BLACK = (0.0, 0.0, 0.0)
WHITE = (1.0, 1.0, 1.0)


def _text(
    c: canvas.Canvas,
    x: float,
    y: float,
    text: str,
    size: float = 9,
    font: str = FONT,
    color: tuple[float, float, float] = BLACK,
    align: str = "left",
) -> None:
    c.setFont(font, size)
    c.setFillColorRGB(*color)
    if align == "right":
        c.drawRightString(x, y, text)
    elif align == "center":
        c.drawCentredString(x, y, text)
    else:
        c.drawString(x, y, text)


def _wrapped(
    c: canvas.Canvas,
    y: float,
    text: str,
    size: float,
    color: tuple[float, float, float],
    leading: float,
) -> float:
    for line in simpleSplit(text, FONT, size, RIGHT - LEFT):
        _text(c, LEFT, y, line, size=size, color=color)
        y -= leading
    return y


def _watermark(c: canvas.Canvas) -> None:
    _text(c, PAGE_W / 2, PAGE_H - 62, WATERMARK, size=40, font=BOLD, color=LIGHT, align="center")
    _text(c, LEFT, PAGE_H - 80, DISCLAIMER, size=7, color=GRAY)
    _text(c, LEFT, 30, f"{WATERMARK} - generated test data - page 1 of 1", size=7, color=GRAY)


def render_pdf(inv: Invoice) -> bytes:
    f = inv.fields
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4, invariant=1, pageCompression=1)
    c.setTitle(f"Invoice {f.invoice_number}")
    c.setAuthor(f.vendor_name)
    c.setCreator("invoice-agent synth")
    if inv.metadata_injection:
        c.setSubject(inv.metadata_injection)
        c.setKeywords(inv.metadata_injection)
    else:
        c.setSubject(f"Invoice {f.invoice_number} from {f.vendor_name}")
        c.setKeywords("invoice, synthetic")

    _watermark(c)

    # Vendor
    y = PAGE_H - 110
    _text(c, LEFT, y, f.vendor_name, size=12, font=BOLD)
    _text(c, LEFT, y - 14, f.vendor_address)
    _text(c, LEFT, y - 26, f"VAT ID: {f.vendor_vat_id}")
    _text(c, LEFT, y - 38, f"Country: {f.vendor_country} ({COUNTRIES[f.vendor_country][1]})")

    # Header block
    y = PAGE_H - 175
    _text(c, LEFT, y, "INVOICE", size=18, font=BOLD)
    header = (
        ("Invoice number", f.invoice_number),
        ("Issue date", f.issue_date.isoformat()),
        ("Due date", f.due_date.isoformat()),
        ("PO number", f.po_number),
        ("Currency", f.currency),
    )
    for i, (label, value) in enumerate(header):
        _text(c, 340, y - i * 14, f"{label}:", color=GRAY)
        _text(c, 430, y - i * 14, value, font=BOLD)

    # Buyer
    y = PAGE_H - 260
    _text(c, LEFT, y, "Bill to:", color=GRAY)
    for i, line in enumerate(BUYER):
        _text(c, LEFT, y - 12 * (i + 1), line)

    # Lines table
    y = PAGE_H - 330
    cols = (("#", LEFT, "left"), ("SKU", 70, "left"), ("Description", 140, "left"))
    for label, x, align in cols:
        _text(c, x, y, label, font=BOLD, align=align)
    _text(c, 400, y, "Qty", font=BOLD, align="right")
    _text(c, 475, y, "Unit price", font=BOLD, align="right")
    _text(c, RIGHT, y, "Line total", font=BOLD, align="right")
    c.setStrokeColorRGB(*GRAY)
    c.line(LEFT, y - 5, RIGHT, y - 5)
    for ln in f.lines:
        y -= 18
        _text(c, LEFT, y, str(ln.line_no))
        _text(c, 70, y, ln.sku)
        _text(c, 140, y, ln.description)
        _text(c, 400, y, fmt_qty(ln.quantity), align="right")
        _text(c, 475, y, fmt_money(ln.unit_price), align="right")
        _text(c, RIGHT, y, fmt_money(ln.line_total), align="right")
    c.line(LEFT, y - 8, RIGHT, y - 8)

    # Totals
    y -= 30
    totals = (
        ("Subtotal", fmt_money(f.subtotal), FONT),
        (f"VAT rate {fmt_money(f.vat_rate)}%", fmt_money(f.vat_amount), FONT),
        (f"Total {f.currency}", fmt_money(f.total), BOLD),
    )
    for label, value, font in totals:
        _text(c, 400, y, label, font=font)
        _text(c, RIGHT, y, value, font=font, align="right")
        y -= 16

    # Payment
    y -= 20
    _text(c, LEFT, y, "Payment by bank transfer to:", color=GRAY)
    _text(c, LEFT, y - 14, f"IBAN: {f.iban}", font=BOLD)
    _text(
        c,
        LEFT,
        y - 28,
        f"Payment terms: {inv.payment_days} days from the invoice date. "
        f"Please quote {f.invoice_number} with your payment.",
    )
    y -= 60

    if inv.visible_note:
        _wrapped(c, y, f"Note: {inv.visible_note}", size=9, color=BLACK, leading=12)

    for hidden in inv.hidden_texts:
        if hidden.kind == "white":
            _wrapped(c, 180, hidden.text, size=8, color=WHITE, leading=10)
        else:
            _text(c, LEFT, 60, hidden.text, size=1, color=BLACK)

    c.showPage()
    c.save()
    return buf.getvalue()
